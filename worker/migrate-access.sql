-- ============================================================================
--  เพิ่ม "สิทธิ์เข้าใช้งาน" (can_login) ให้ฐานข้อมูลที่ขึ้นระบบไปแล้ว
--  รันด้วย: wrangler d1 execute gemba-audit --file=./migrate-access.sql --remote
--
--  ทำไมต้องมีคอลัมน์นี้
--    รหัสเข้าระบบคือรหัสพนักงาน ซึ่งเดาได้ไม่ยาก (T-815 · G-245)
--    ถ้าปล่อยให้ทุกคนในทะเบียน 393 คนล็อกอินได้ ใครก็เข้าแทนกันได้
--    จึงให้ผู้ดูแลระบบ "กำหนด" เป็นรายคนว่าใครเข้าได้ ค่าตั้งต้นของคนใหม่คือเข้าไม่ได้
--
--  ต่างจาก is_active อย่างไร
--    is_active = ยังเป็นพนักงานอยู่ไหม (ลาออกแล้วปิด)
--    can_login = คนนี้ได้รับสิทธิ์ใช้แอปนี้หรือไม่
--    พนักงาน 329 คนยังอยู่ในทะเบียนเพื่อใส่เป็น "ผู้ร่วมเดิน" ได้ แต่ล็อกอินไม่ได้
--
--  รันซ้ำได้: ALTER TABLE จะฟ้อง "duplicate column name" ถ้าเคยรันแล้ว
--  ให้ข้ามบรรทัดนั้นแล้วรัน UPDATE ต่อได้เลย
-- ============================================================================

ALTER TABLE managers ADD COLUMN can_login INTEGER NOT NULL DEFAULT 0 CHECK (can_login IN (0, 1));

-- เปิดสิทธิ์ให้ระดับหัวหน้าขึ้นไปที่ยังทำงานอยู่ (64 คน)
-- พนักงานระดับปฏิบัติการไม่ได้เปิด — ผู้ดูแลระบบเปิดเพิ่มรายคนได้ในหน้าตั้งค่า
UPDATE managers
   SET can_login = 1
 WHERE is_active = 1
   AND position IN ('ผู้จัดการ', 'ผู้ดูแลแผนก', 'หัวหน้าทีม', 'ผู้ดูแลระบบ', 'เจ้าหน้าที่ความปลอดภัย');

-- ผู้ดูแลระบบต้องเข้าได้เสมอ แม้ตำแหน่งในทะเบียนจะเขียนไว้ต่างออกไป
UPDATE managers
   SET can_login = 1
 WHERE UPPER(REPLACE(manager_code, '-', '')) IN (
         SELECT UPPER(REPLACE(admin_code, '-', '')) FROM superusers
       );
